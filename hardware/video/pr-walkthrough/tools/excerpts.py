"""The walkthrough's code excerpts, read verbatim from the working tree (never retyped).

    python3 tools/excerpts.py     # -> assets/code.js (window.__CODE = {name: {path, from, html: [line, ...]}})

Each excerpt is anchored on a line of code (not a line number, which drifts) and must match exactly once. Lines are
HTML-escaped, then lightly highlighted: comments, strings and numbers. Re-run before every build.
"""
