TOKEN = re.compile(r'(?P<c>//.*$|#.*$)|(?P<s>"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'|`[^`]*`)|(?P<n>\b\d+(?:\.\d+)?\b)')


def light(line, lang):
    out, i = [], 0
    for m in TOKEN.finditer(line):
        if m.group("c") and (lang == "cs" or lang in ("ts", "cpp")) and m.group("c").startswith("#"):
            continue   # '#' is not a comment in C#/TS/C++ (it is in YAML, which isn't excerpted)
        out.append(html.escape(line[i:m.start()]))
        kind = "c" if m.group("c") else "s" if m.group("s") else "n"
        out.append(f'<span class="t{kind}">{html.escape(m.group(0))}</span>')
        i = m.end()
    out.append(html.escape(line[i:]))
    return "".join(out)


if __name__ == "__main__":
    code = {}
    for name, (path, anchor, before, n) in EXCERPTS.items():
        lines = (REPO / path).read_text().splitlines()
        hits = [i for i, l in enumerate(lines) if anchor in l]
        assert len(hits) == 1, f"{name}: anchor found {len(hits)} times in {path}"
        a = hits[0] - before
        chunk = lines[a:a + n]
        indent = min(len(l) - len(l.lstrip()) for l in chunk if l.strip())
        lang = {".cs": "cs", ".ts": "ts", ".tsx": "ts", ".cpp": "cpp", ".h": "cpp"}[Path(path).suffix]
        code[name] = {"path": path, "from": a + 1, "html": [light(l[indent:], lang) for l in chunk]}
    (ROOT / "assets/code.js").write_text("// Generated by tools/excerpts.py from the working tree -- do not edit.\n"
                                         f"window.__CODE = {json.dumps(code, indent=1)};\n")
    print(f"ok: {len(code)} excerpts -> assets/code.js")
