# PlatformIO post-script: builds the LP-core program src/lp/blink.c (the status LED in deep sleep) the way
# ESP-IDF's ulp component does (components/ulp/cmake/IDFULPProject.cmake), and writes $BUILD_DIR/lp/lp_blink.h:
# the binary as a byte array plus each shared variable's address (LP_<name>) for src/goal/device.cpp.
import os
import re
import subprocess

Import("env", "projenv")  # noqa: F821  (SCons; projenv builds src/)


def build():
    platform = env.PioPlatform()  # noqa: F821
    idf = platform.get_package_dir("framework-espidf")
    bin_dir = os.path.join(platform.get_package_dir("toolchain-riscv32-esp"), "bin")
    tool = lambda name: os.path.join(bin_dir, "riscv32-esp-elf-" + name)
    out = os.path.join(env.subst("$BUILD_DIR"), "lp")  # noqa: F821
    os.makedirs(out, exist_ok=True)
    lp = os.path.join(idf, "components/ulp/lp_core")
    sources = [os.path.join(env.subst("$PROJECT_SRC_DIR"), "lp/blink.c")] + [os.path.join(lp, s) for s in (  # noqa: F821
        "lp_core/start.S", "lp_core/vector.S", "lp_core/port/esp32c6/vector_table.S",
        "shared/ulp_lp_core_memory_shared.c", "shared/ulp_lp_core_lp_uart_shared.c", "shared/ulp_lp_core_lp_timer_shared.c",
        "lp_core/lp_core_startup.c", "lp_core/lp_core_utils.c", "lp_core/lp_core_uart.c", "lp_core/lp_core_print.c",
        "lp_core/lp_core_panic.c", "lp_core/lp_core_interrupt.c", "lp_core/lp_core_i2c.c", "lp_core/lp_core_spi.c",
        "lp_core/lp_core_ubsan.c", "shared/ulp_lp_core_lp_adc_shared.c", "shared/ulp_lp_core_lp_vad_shared.c",
        "shared/ulp_lp_core_critical_section_shared.c")]
    # The main build's include dirs (soc, hal, esp_rom ... and sdkconfig.h for this sdkconfig), plus the LP core's own
    incs = [env.subst(p) for p in env["CPPPATH"]] + [os.path.join(lp, "lp_core/include"), os.path.join(lp, "shared/include"),  # noqa: F821
                                                     os.path.join(lp, "include"), os.path.join(idf, "components/esp_system/ld")]
    flags = ["-Os", "-march=rv32imac_zicsr_zifencei", "-mdiv", "-fdata-sections", "-ffunction-sections", "-DIS_ULP_COCPU"]
    flags += ["-I" + i for i in incs]
    elf, binf, hdr = (os.path.join(out, n) for n in ("blink.elf", "blink.bin", "lp_blink.h"))

    def run(*cmd):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            raise SystemExit(f"lp_build: {' '.join(cmd[:3])} ... failed:\n{r.stderr[-3000:]}")
        return r.stdout

    ld = os.path.join(out, "lp_core_riscv.ld")
    run(tool("gcc"), "-D__ASSEMBLER__", "-E", "-P", "-xc", "-o", ld, *["-I" + i for i in incs],
        os.path.join(idf, "components/ulp/ld/lp_core_riscv.ld"))
    objs = []
    for src in sources:
        obj = os.path.join(out, os.path.basename(src) + ".o")
        run(tool("gcc"), *flags, *(["-x", "assembler-with-cpp"] if src.endswith(".S") else []), "-c", src, "-o", obj)
        objs.append(obj)
    links = ["-T", ld, "-T", os.path.join(idf, "components/soc/esp32c6/ld/esp32c6.peripherals.ld")]
    run(tool("gcc"), "-march=rv32imac_zicsr_zifencei", "--specs=nano.specs", "--specs=nosys.specs", "-nostartfiles",
        "-Wl,--gc-sections", "-Wl,--no-warn-rwx-segments", *links, "-o", elf, *objs)
    run(tool("objcopy"), "-O", "binary", elf, binf)
    syms = {m.group(2): m.group(1) for m in re.finditer(r"^([0-9a-f]+) [BbDd] (\w+)$", run(tool("nm"), elf), re.M)}
    data = open(binf, "rb").read()
    with open(hdr, "w") as f:
        f.write("// GENERATED by tools/lp_build.py from src/lp/blink.c -- DO NOT EDIT.\n#pragma once\n#include <stdint.h>\n")
        f.write(f"static const uint8_t LP_BLINK_BIN[{len(data)}] = {{{', '.join(str(b) for b in data)}}};\n")
        for name in ("blinks", "blink_ms", "gap_ms", "period_ms"):
            f.write(f"#define LP_{name} ((volatile uint32_t*)0x{syms[name]})\n")
    print(f"lp_build: LP core program {len(data)} bytes")
    # lp_blink.h, and ulp_lp_core.h + libulp for the main core (the prebuilt libs' include list doesn't carry it)
    for e in (env, projenv):  # noqa: F821
        e.Append(CPPPATH=[out, os.path.join(lp, "include"), os.path.join(idf, "components/ulp/ulp_common/include")])
    env.Append(LIBS=["ulp"])  # noqa: F821  (built by the IDF lib rebuild, not in the prebuilt link list)


# pioarduino's IDF lib rebuild (custom_sdkconfig) runs this script too, in a dummy project: nothing to build there
if os.path.isfile(os.path.join(env.subst("$PROJECT_SRC_DIR"), "lp/blink.c")):  # noqa: F821
    build()
